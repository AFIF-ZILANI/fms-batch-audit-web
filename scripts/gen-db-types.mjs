// Generates src/lib/database.types.ts in the same shape as `supabase gen types typescript`,
// straight from a Postgres database (no Docker / Supabase CLI needed).
//
//   DATABASE_URL=postgresql://user:pass@host:5432/db npm run gen:types
//
// Point it at a database that has supabase/migrations applied (local or Supabase).
import { writeFileSync } from 'node:fs'
import pg from 'pg'

const url = process.env.DATABASE_URL
if (!url) {
  console.error('Set DATABASE_URL')
  process.exit(1)
}
const OUT = new URL('../src/lib/database.types.ts', import.meta.url)
const client = new pg.Client({ connectionString: url })
await client.connect()

const q = async (sql) => (await client.query(sql)).rows

const enums = await q(`
  select t.typname as name, array_agg(e.enumlabel::text order by e.enumsortorder) as labels
  from pg_type t join pg_enum e on e.enumtypid = t.oid join pg_namespace n on n.oid = t.typnamespace
  where n.nspname = 'public' group by t.typname order by t.typname`)
const enumNames = new Set(enums.map((e) => e.name))

const columns = await q(`
  select c.relname as rel, c.relkind as kind, a.attname as col, a.attnum as pos,
         format_type(a.atttypid, a.atttypmod) as type, t.typname as udt,
         not a.attnotnull as nullable, a.atthasdef as has_default,
         a.attidentity as identity, a.attgenerated as generated
  from pg_attribute a
  join pg_class c on c.oid = a.attrelid
  join pg_namespace n on n.oid = c.relnamespace
  join pg_type t on t.oid = a.atttypid
  where n.nspname = 'public' and c.relkind in ('r', 'v') and a.attnum > 0 and not a.attisdropped
  order by c.relname, a.attnum`)

const fks = await q(`
  select con.conname as name, c.relname as rel, rc.relname as ref_rel,
         array(select attname::text from unnest(con.conkey) k join pg_attribute on attrelid = con.conrelid and attnum = k) as cols,
         array(select attname::text from unnest(con.confkey) k join pg_attribute on attrelid = con.confrelid and attnum = k) as ref_cols
  from pg_constraint con
  join pg_class c on c.oid = con.conrelid join pg_class rc on rc.oid = con.confrelid
  join pg_namespace n on n.oid = c.relnamespace
  where con.contype = 'f' and n.nspname = 'public' order by con.conname`)

const functions = await q(`
  select p.proname as name, pg_get_function_result(p.oid) as returns,
         coalesce(p.proargnames::text[], array[]::text[]) as arg_names, p.pronargdefaults as n_defaults,
         array(select format_type(t, null) from unnest(p.proargtypes) with ordinality as a(t, i) order by i) as arg_types,
         array(select tt.typname::text from unnest(p.proargtypes) with ordinality as a(t, i) join pg_type tt on tt.oid = a.t order by a.i) as arg_udts
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prokind = 'f' and pg_get_function_result(p.oid) <> 'trigger'
  order by p.proname`)

await client.end()

function tsType(type, udt) {
  if (enumNames.has(udt)) return `Database["public"]["Enums"]["${udt}"]`
  if (/^(smallint|integer|bigint|numeric|real|double precision)/.test(type)) return 'number'
  if (type === 'boolean') return 'boolean'
  if (/^(json|jsonb)$/.test(type)) return 'Json'
  if (type.endsWith('[]')) return `${tsType(type.slice(0, -2), udt.replace(/^_/, ''))}[]`
  return 'string' // text, date, timestamptz, uuid, …
}

const byRel = new Map()
for (const c of columns) {
  if (!byRel.has(c.rel)) byRel.set(c.rel, { kind: c.kind, cols: [] })
  byRel.get(c.rel).cols.push(c)
}

const ind = (n) => '  '.repeat(n)
const lines = []
const relationships = (rel) => {
  const list = fks.filter((f) => f.rel === rel)
  if (!list.length) return `${ind(4)}Relationships: []`
  const items = list.map(
    (f) =>
      `${ind(5)}{\n${ind(6)}foreignKeyName: "${f.name}"\n${ind(6)}columns: [${f.cols.map((c) => `"${c}"`).join(', ')}]\n` +
      `${ind(6)}isOneToOne: false\n${ind(6)}referencedRelation: "${f.ref_rel}"\n` +
      `${ind(6)}referencedColumns: [${f.ref_cols.map((c) => `"${c}"`).join(', ')}]\n${ind(5)}},`,
  )
  return `${ind(4)}Relationships: [\n${items.join('\n')}\n${ind(4)}]`
}

lines.push(`// Generated by scripts/gen-db-types.mjs — do not edit by hand.`)
lines.push(`export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[]`)
lines.push('')
lines.push('export type Database = {')
lines.push(`${ind(1)}public: {`)

lines.push(`${ind(2)}Tables: {`)
for (const [rel, { kind, cols }] of byRel) {
  if (kind !== 'r') continue
  lines.push(`${ind(3)}${rel}: {`)
  lines.push(`${ind(4)}Row: {`)
  for (const c of cols) lines.push(`${ind(5)}${c.col}: ${tsType(c.type, c.udt)}${c.nullable ? ' | null' : ''}`)
  lines.push(`${ind(4)}}`)
  for (const mode of ['Insert', 'Update']) {
    lines.push(`${ind(4)}${mode}: {`)
    for (const c of cols) {
      const readonly = c.identity === 'a' || c.generated === 's'
      const optional = mode === 'Update' || c.nullable || c.has_default || c.identity !== ''
      const t = readonly ? 'never' : `${tsType(c.type, c.udt)}${c.nullable ? ' | null' : ''}`
      lines.push(`${ind(5)}${c.col}${optional || readonly ? '?' : ''}: ${t}`)
    }
    lines.push(`${ind(4)}}`)
  }
  lines.push(relationships(rel))
  lines.push(`${ind(3)}}`)
}
lines.push(`${ind(2)}}`)

lines.push(`${ind(2)}Views: {`)
for (const [rel, { kind, cols }] of byRel) {
  if (kind !== 'v') continue
  lines.push(`${ind(3)}${rel}: {`)
  lines.push(`${ind(4)}Row: {`)
  for (const c of cols) lines.push(`${ind(5)}${c.col}: ${tsType(c.type, c.udt)} | null`)
  lines.push(`${ind(4)}}`)
  lines.push(`${ind(4)}Relationships: []`)
  lines.push(`${ind(3)}}`)
}
lines.push(`${ind(2)}}`)

lines.push(`${ind(2)}Functions: {`)
for (const f of functions) {
  const n = f.arg_names.length
  const args = f.arg_names.map((a, i) => {
    const optional = i >= n - f.n_defaults
    return `${ind(5)}${a}${optional ? '?' : ''}: ${tsType(f.arg_types[i], f.arg_udts[i])}`
  })
  lines.push(`${ind(3)}${f.name}: {`)
  lines.push(`${ind(4)}Args: {\n${args.join('\n')}\n${ind(4)}}`)
  lines.push(`${ind(4)}Returns: ${tsType(f.returns, f.returns)}`)
  lines.push(`${ind(3)}}`)
}
lines.push(`${ind(2)}}`)

lines.push(`${ind(2)}Enums: {`)
for (const e of enums) lines.push(`${ind(3)}${e.name}: ${e.labels.map((l) => `"${l}"`).join(' | ')}`)
lines.push(`${ind(2)}}`)
lines.push(`${ind(2)}CompositeTypes: { [_ in never]: never }`)
lines.push(`${ind(1)}}`)
lines.push('}')
lines.push('')
lines.push(`type PublicSchema = Database["public"]`)
lines.push(`export type Tables<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Row"]`)
lines.push(`export type TablesInsert<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Insert"]`)
lines.push(`export type TablesUpdate<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Update"]`)
lines.push(`export type Views<T extends keyof PublicSchema["Views"]> = PublicSchema["Views"][T]["Row"]`)
lines.push(`export type Enums<T extends keyof PublicSchema["Enums"]> = PublicSchema["Enums"][T]`)
lines.push('')

writeFileSync(OUT, lines.join('\n'))
console.log(`Wrote ${OUT.pathname}`)
